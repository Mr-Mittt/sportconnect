import { expect, test } from '@playwright/test';
import { themeStoryIds, themeStoryName, themeStoryUrl } from '../mocks/themeStorybook.ts';

/*
 * AUTH-15: visual-regression coverage for the Keycloak-hosted pages (the Keycloakify theme in
 * client/keycloak-theme), replacing the 21 baselines AUTH-14 removed with the client's own auth
 * screens. Playwright captures the *static theme Storybook* (no Keycloak needed), one baseline per
 * story per breakpoint in English, plus the two entry pages (login, register) in Vietnamese.
 *
 * Needs the theme Storybook built first: `pnpm build-theme-storybook` (the spec fails loudly with
 * that hint otherwise — it never skips silently). Baselines are rendered on Linux CI only: they are
 * generated by the `update-baselines` GitHub dispatch, never on a Windows host.
 *
 * The community illustration floats continuously and inputs show a blinking caret, so every shot
 * disables CSS animations and blurs the active element first.
 */

const breakpoints = [375, 768, 1280] as const;
const viEntryPages = ['login', 'register'];

const stories = themeStoryIds().map((id) => ({ id, name: themeStoryName(id) }));

async function capture(page: import('@playwright/test').Page, id: string, locale: 'en' | 'vi') {
  await page.goto(themeStoryUrl(id, locale));
  await expect(page.locator('#storybook-root h1, #storybook-root form').first()).toBeVisible();
  await page.evaluate('document.activeElement?.blur()');
  await page.evaluate('document.fonts.ready');
}

for (const width of breakpoints) {
  for (const { id, name } of stories) {
    test(`theme ${name} @ ${width}px`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      await capture(page, id, 'en');
      await expect(page).toHaveScreenshot(`auth-theme-${name}-${width}.png`, {
        fullPage: true,
        animations: 'disabled',
      });
    });
  }

  for (const { id, name } of stories.filter(({ name }) => viEntryPages.includes(name))) {
    test(`theme ${name} (vi) @ ${width}px`, async ({ page }) => {
      await page.setViewportSize({ width, height: 900 });
      await capture(page, id, 'vi');
      await expect(page).toHaveScreenshot(`auth-theme-${name}-vi-${width}.png`, {
        fullPage: true,
        animations: 'disabled',
      });
    });
  }
}
